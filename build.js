#!/usr/bin/env node
/*
 * Builds everything in dist/ from palette.json (the paints) and lib/roles.js
 * (what each color is for). Run with `npm run build` or `node build.js`.
 */
const fs = require('fs');
const path = require('path');
const R = require('./lib/roles.js');
const C = require('./lib/color.js');
const pkg = require('./package.json');

const DIST = path.join(__dirname, 'dist');
const NAME = 'Renegade';
const AUTHOR = 'dr-frmr';
const CREDIT = "after Julie Mehretu, Retopistics: A Renegade Excavation";
const { paint: P, role, dark, syntax, base16, base24, ansi, ansiDark, readableOn } = R;

fs.rmSync(DIST, { recursive: true, force: true });
const write = (rel, text) => {
  const file = path.join(DIST, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text.endsWith('\n') ? text : text + '\n');
};
const json = (o) => JSON.stringify(o, null, 2);
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const camelToKebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

// ---- tokens.json: the paints plus every role, resolved (W3C DTCG) ----
const group = (o) => ({ $type: 'color', ...Object.fromEntries(Object.entries(o).map(([k, v]) => [camelToKebab(k), { $value: v }])) });
write('tokens.json', json({
  $description: `${NAME}, a light color theme ${CREDIT}. Generated by build.js.`,
  paint: require('./palette.json').paint,
  role: group(role),
  syntax: group(syntax),
  ansi: group(Object.fromEntries(ansi.map((c, i) => [`ansi-${i}`, c]))),
}));

// ---- Base16 / Base24 schemes (tinted-theming spec 0.11) ----
const scheme = (system, slots) => [
  `system: "${system}"`, `name: "${NAME}"`, `slug: "renegade"`, `author: "${AUTHOR}"`,
  `description: "A light theme ${CREDIT}"`, `variant: "light"`, 'palette:',
  ...Object.entries(slots).map(([k, v]) => `  ${k}: "${v}"`),
].join('\n');
write('base16/renegade.yaml', scheme('base16', base16));
write('base24/renegade.yaml', scheme('base24', base24));

// ---- CSS custom properties ----
write('css/renegade.css', [
  `/* ${NAME}: a light color theme ${CREDIT}. */`, ':root {',
  ...Object.entries(P).map(([k, v]) => `  --renegade-${k}: ${v};`), '',
  ...Object.entries(role).map(([k, v]) => `  --renegade-${camelToKebab(k)}: ${v};`), '',
  ...Object.entries(syntax).map(([k, v]) => `  --renegade-syntax-${k}: ${v};`), '}',
].join('\n'));

// ---- VS Code color theme (also used as bb's code theme) ----
const S = syntax;
const tokenColors = [
  [['comment', 'punctuation.definition.comment'], S.comment, 'italic'],
  [['keyword', 'storage', 'storage.type', 'storage.modifier', 'keyword.control'], S.keyword],
  [['keyword.operator', 'punctuation.accessor'], S.operator],
  [['entity.name.function', 'support.function', 'meta.function-call entity.name.function'], S.function],
  [['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class'], S.type],
  [['string', 'string.quoted', 'string.template', 'punctuation.definition.string'], S.string],
  [['string.regexp'], S.regexp],
  [['constant.character.escape'], S.escape],
  [['constant.numeric'], S.number],
  [['constant.language', 'constant.other', 'variable.other.constant'], S.constant],
  [['entity.name.namespace', 'entity.name.module', 'entity.name.scope-resolution'], S.namespace],
  [['variable', 'variable.other.readwrite', 'meta.object-literal.key'], S.variable],
  [['variable.parameter'], S.parameter],
  [['variable.language', 'support.variable', 'support.constant'], S.builtin],
  [['meta.decorator', 'entity.name.function.decorator', 'punctuation.decorator'], S.decorator],
  [['entity.name.tag'], S.tag],
  [['entity.other.attribute-name'], S.attribute],
  [['markup.heading'], P['blue-lines'], 'bold'],
  [['markup.bold'], role.text, 'bold'],
  [['markup.italic'], role.text, 'italic'],
  [['markup.inserted'], role.added],
  [['markup.deleted'], role.removed],
  [['markup.changed'], role.warning],
  [['markup.underline.link'], role.accent],
  [['invalid'], role.dangerText],
].map(([scope, foreground, fontStyle]) => ({ scope, settings: fontStyle ? { foreground, fontStyle } : { foreground } }));
const a = (hex, alpha) => hex + Math.round(alpha * 255).toString(16).padStart(2, '0');
const vscode = {
  $schema: 'vscode://schemas/color-theme',
  name: NAME, type: 'light', semanticHighlighting: true,
  colors: {
    'editor.background': role.background, 'editor.foreground': role.text, foreground: role.text,
    'editor.selectionBackground': role.highlight, 'editor.inactiveSelectionBackground': a(role.highlightStrong, 0.2),
    'editor.selectionHighlightBackground': a(role.highlightStrong, 0.18), 'editor.wordHighlightBackground': a(role.highlightStrong, 0.18),
    'editor.findMatchBackground': a(P['saffron-arcs'], 0.45), 'editor.findMatchHighlightBackground': a(P['saffron-arcs'], 0.25),
    'editor.lineHighlightBackground': a(role.text, 0.05), 'editorCursor.foreground': role.accent,
    'editorLineNumber.foreground': role.textMuted, 'editorLineNumber.activeForeground': role.text,
    'editorIndentGuide.background1': a(role.text, 0.1), 'editorIndentGuide.activeBackground1': a(role.text, 0.25),
    'editorWhitespace.foreground': a(role.text, 0.2), 'editorBracketMatch.background': a(role.highlightStrong, 0.2),
    'editorGutter.addedBackground': P['chartreuse'], 'editorGutter.modifiedBackground': P['saffron-arcs'], 'editorGutter.deletedBackground': P['burst-red'],
    'diffEditor.insertedTextBackground': a(P['chartreuse'], 0.25), 'diffEditor.removedTextBackground': a(P['burst-red'], 0.15),
    'diffEditor.insertedLineBackground': a(P['chartreuse'], 0.15), 'diffEditor.removedLineBackground': a(P['burst-red'], 0.08),
    'editorError.foreground': role.dangerText, 'editorWarning.foreground': role.warning, 'editorInfo.foreground': role.accent,
    focusBorder: role.accent, 'selection.background': role.highlight, 'textLink.foreground': role.accent,
    'sideBar.background': role.surface, 'sideBar.foreground': role.text, 'sideBar.border': role.border,
    'activityBar.background': role.surface, 'activityBar.foreground': role.text, 'activityBar.border': role.border,
    'activityBarBadge.background': role.highlightStrong, 'activityBarBadge.foreground': role.text,
    'titleBar.activeBackground': role.frame, 'titleBar.activeForeground': role.text, 'titleBar.inactiveBackground': role.surface,
    'tab.activeBackground': role.background, 'tab.inactiveBackground': role.surface, 'tab.activeForeground': role.text,
    'tab.inactiveForeground': role.textMuted, 'tab.border': role.border, 'tab.activeBorderTop': role.highlightStrong,
    'editorGroupHeader.tabsBackground': role.surface, 'statusBar.background': role.frame, 'statusBar.foreground': role.text,
    'statusBar.noFolderBackground': role.frame, 'panel.background': role.background, 'panel.border': role.border,
    'list.activeSelectionBackground': role.highlight, 'list.activeSelectionForeground': role.text,
    'list.inactiveSelectionBackground': a(role.highlightStrong, 0.2), 'list.hoverBackground': a(role.text, 0.06),
    'input.background': role.surface, 'input.border': role.border, 'input.foreground': role.text,
    'dropdown.background': role.surface, 'dropdown.border': role.border,
    'button.background': role.accent, 'button.foreground': role.onAccent, 'badge.background': role.highlightStrong, 'badge.foreground': role.text,
    'terminal.background': role.background, 'terminal.foreground': role.text,
    ...Object.fromEntries(['Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White'].flatMap((n, i) => [[`terminal.ansi${n}`, ansi[i]], [`terminal.ansiBright${n}`, ansi[i + 8]]])),
  },
  tokenColors,
};
write('vscode/themes/renegade-color-theme.json', json(vscode));
write('vscode/package.json', json({
  name: 'renegade-theme', displayName: NAME, description: `A light color theme ${CREDIT}`, version: pkg.version,
  publisher: AUTHOR, engines: { vscode: '^1.70.0' }, categories: ['Themes'],
  contributes: { themes: [{ label: NAME, uiTheme: 'vs', path: './themes/renegade-color-theme.json' }] },
}));

// ---- bb ----
const bbBlock = (sel, t, ans, extra = '') => `${sel} {
  --canvas: ${t.background};
  --ink: ${t.text};
  --primary: ${t.accent};
  --primary-foreground: ${t.onAccent};
${extra}  --destructive: ${t.danger};
  --destructive-foreground: ${t.onAccent};
  --destructive-text: ${t.dangerText};
  --warning: ${t.warning};
  --warning-text: ${t.warningText || t.warning};
  --attention: ${t.attention};
  --success: ${t.success};
  --diff-added: ${t.added};
  --diff-removed: ${t.removed};
  --pr-merged: ${t.merged};
  --file-accent: ${t.path};
${ans.map((c, i) => `  --ansi-${i}: ${c};`).join('\n')}
${ans.map((c, i) => `  --ansi-bg-fg-${i}: ${readableOn(c)};`).join('\n')}
}
`;
write('bb/theme.css', `/* ${NAME}: a light bb theme ${CREDIT}. Generated by build.js. */

${bbBlock(':root,\n.light', role, ansi, `  --surface-selected: ${role.highlight};
  --surface-selected-border: ${role.highlightStrong};
  --sidebar-accent: ${role.highlight};
  --sidebar-accent-foreground: ${role.text};
  --state-active: color-mix(in srgb, ${role.highlightStrong} 38%, transparent);
  --muted-foreground: color-mix(in oklch, var(--ink) 72%, var(--canvas));
  --subtle-foreground: color-mix(in oklch, var(--ink) 60%, var(--canvas));
  --readback-foreground: color-mix(in oklch, var(--ink) 66%, var(--canvas));
`)}
:root:not(.dark) ::selection {
  background-color: ${role.highlight};
  color: ${role.text};
}

/* Dark mode flips the painting: the navy becomes the ground, the ground the ink. */
${bbBlock('.dark', dark, ansiDark)}`);
write('bb/theme.json', json({ codeTheme: { light: 'renegade-code.json', dark: 'pierre-dark' } }));
write('bb/renegade-code.json', json(vscode));

// ---- Chrome theme ----
const chromeColors = {
  frame: role.frame, frame_inactive: C.shade('pink-plane', 0.7),
  toolbar: role.background, toolbar_text: role.text, toolbar_button_icon: role.textMuted,
  tab_text: role.text, tab_background_text: role.textMuted, tab_background_text_inactive: ansi[8],
  bookmark_text: role.text, omnibox_background: role.surface, omnibox_text: role.text,
  ntp_background: role.background, ntp_text: role.text, ntp_link: role.accent, ntp_header: role.frame, ntp_section: role.background,
};
write('chrome-theme/manifest.json', json({
  manifest_version: 3, name: NAME, version: pkg.version, description: `A light Chrome theme ${CREDIT}.`,
  theme: { colors: Object.fromEntries(Object.entries(chromeColors).map(([k, v]) => [k, rgb(v)])) },
}));

// ---- Chrome extension that repaints websites ----
const sites = path.join(__dirname, 'sites');
write('chrome-sites/renegade.js', `globalThis.RENEGADE_PAINT = ${JSON.stringify(P)};\n` + fs.readFileSync(path.join(__dirname, 'lib/color.js'), 'utf8'));
for (const f of ['repaint.js', 'shadow.js', 'github.js', 'x.js']) write(`chrome-sites/${f}`, fs.readFileSync(path.join(sites, f), 'utf8'));
write('chrome-sites/guard.css', `/* Until repaint.js has repainted the page, show only the ground, so the original
   colors never flash. repaint.js sets data-renegade when it's done (or after 1.5s). */
html { background: ${role.background} !important; color-scheme: light !important; }
html:not([data-renegade]) body { visibility: hidden !important; }

/* Selected text: the pink plane thinned over the ground. */
::selection { background-color: ${role.highlight} !important; color: ${role.text} !important; }

/* Chrome draws native audio players outside the page's stylesheets. */
audio::-webkit-media-controls-panel { background-color: ${C.mapColor('#f1f3f4')} !important; }`);
const X = ['https://x.com/*', 'https://*.x.com/*', 'https://twitter.com/*', 'https://*.twitter.com/*'];
write('chrome-sites/manifest.json', json({
  manifest_version: 3, name: `${NAME} Sites`, version: pkg.version,
  description: `Repaints GitHub and X in the ${NAME} colors, ${CREDIT}.`,
  content_scripts: [
    { matches: ['https://github.com/*', 'https://gist.github.com/*'], css: ['guard.css'], js: ['renegade.js', 'repaint.js', 'github.js'], run_at: 'document_start' },
    { matches: X, css: ['guard.css'], js: ['renegade.js', 'repaint.js', 'x.js'], run_at: 'document_start', all_frames: true, match_origin_as_fallback: true },
    { matches: X, js: ['shadow.js'], run_at: 'document_start', world: 'MAIN', all_frames: true, match_origin_as_fallback: true },
  ],
}));

// ---- iTerm2 ----
const it = (hex, alpha = 1) => {
  const [r, g, b] = rgb(hex).map((v) => v / 255);
  return { 'Alpha Component': alpha, 'Blue Component': b, 'Color Space': 'sRGB', 'Green Component': g, 'Red Component': r };
};
const itColors = Object.fromEntries(ansi.map((h, i) => [`Ansi ${i} Color`, it(h)]));
Object.assign(itColors, {
  'Background Color': it(role.background), 'Foreground Color': it(role.text), 'Bold Color': it(role.text),
  'Cursor Color': it(role.accent), 'Cursor Text Color': it(role.onAccent),
  'Selection Color': it(role.highlight), 'Selected Text Color': it(role.text),
  'Link Color': it(role.accent), 'Badge Color': it(P['burst-red'], 0.45),
  'Cursor Guide Color': it(role.text, 0.08), 'Tab Color': it(role.frame),
});
const plistDict = (o, ind) => Object.entries(o).map(([k, v]) => `${ind}<key>${k}</key>\n` + (typeof v === 'object'
  ? `${ind}<dict>\n${plistDict(v, ind + '\t')}\n${ind}</dict>`
  : `${ind}${typeof v === 'number' ? `<real>${v}</real>` : `<string>${v}</string>`}`)).join('\n');
write('iterm2/renegade.itermcolors', `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
${plistDict(itColors, '\t')}
</dict>
</plist>`);

// ---- Slack: system navigation, selected items, presence, notifications ----
write('slack.txt', [role.background, role.highlightStrong, P['chartreuse'], P['burst-red']].map((h) => h.toUpperCase()).join(', '));

// ---- palette.svg, for the README ----
const paints = Object.entries(P);
const cols = 6, w = 150, h = 118, gap = 12, pad = 24;
const rows = Math.ceil(paints.length / cols);
const svgW = pad * 2 + cols * w + (cols - 1) * gap, svgH = pad * 2 + rows * (h + gap) + 40;
const cells = paints.map(([name, hex], i) => {
  const x = pad + (i % cols) * (w + gap), y = pad + Math.floor(i / cols) * (h + gap);
  return `<rect x="${x}" y="${y}" width="${w}" height="76" rx="8" fill="${hex}" stroke="${role.text}" stroke-opacity="0.12"/>` +
    `<text x="${x + 2}" y="${y + 96}" font-size="13" fill="${role.text}">${name.replace(/-/g, ' ')}</text>` +
    `<text x="${x + 2}" y="${y + 113}" font-size="12" fill="${role.textMuted}" font-family="ui-monospace, Menlo, monospace">${hex}</text>`;
}).join('\n  ');
const strip = Object.values(base16).map((hex, i) => `<rect x="${pad + i * ((svgW - 2 * pad) / 16)}" y="${svgH - pad - 24}" width="${(svgW - 2 * pad) / 16}" height="24" fill="${hex}"/>`).join('');
write('palette.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="${svgW}" height="${svgH}" viewBox="0 0 ${svgW} ${svgH}" font-family="-apple-system, system-ui, sans-serif">
  <rect width="100%" height="100%" rx="16" fill="${role.background}"/>
  ${cells}
  ${strip}
</svg>`);

console.log(`built ${NAME} ${pkg.version} into dist/`);
